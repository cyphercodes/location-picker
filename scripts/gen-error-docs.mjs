// Generates docs/errors.md from ERROR_TABLE in src/core/errors.ts (CONTRACT §12.2), the single source of truth for
// error messages, fixes and default levels. The TypeScript module is bundled in memory with esbuild and imported.
//
//   node scripts/gen-error-docs.mjs           rewrite docs/errors.md
//   node scripts/gen-error-docs.mjs --check   fail if docs/errors.md is missing or out of date
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const SOURCE = 'src/core/errors.ts';
const OUTPUT = 'docs/errors.md';
const LEVELS = {
  error: 'logged with `console.error` when unhandled',
  warn: 'logged with `console.warn` when unhandled',
  silent: 'never logged',
};
const check = process.argv.includes('--check');

if (!existsSync(SOURCE)) {
  console.error(`${SOURCE} does not exist yet, so ${OUTPUT} cannot be generated.`);
  process.exit(1);
}

const table = await loadErrorTable();
const markdown = await format(render(table), {
  ...(await resolveConfig(OUTPUT)),
  parser: 'markdown',
});

if (check) {
  const committed = existsSync(OUTPUT) ? await readFile(OUTPUT, 'utf8') : '';
  if (committed !== markdown) {
    console.error(
      `${OUTPUT} is out of date with ${SOURCE}. Run \`node scripts/gen-error-docs.mjs\` and commit it.`,
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(OUTPUT, markdown);
  console.log(`${OUTPUT}: ${Object.keys(table).length} codes`);
}

async function loadErrorTable() {
  const result = await build({
    entryPoints: [SOURCE],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    write: false,
    logLevel: 'silent',
    // Styles are irrelevant here; `*.css?inline` imports (if any) become empty strings.
    plugins: [
      {
        name: 'css-stub',
        setup(b) {
          b.onResolve({ filter: /\.css(\?inline)?$/ }, (args) => ({
            path: args.path,
            namespace: 'css-stub',
          }));
          b.onLoad({ filter: /.*/, namespace: 'css-stub' }, () => ({
            contents: '',
            loader: 'text',
          }));
        },
      },
    ],
  });
  const code = result.outputFiles[0].text;
  const module = await import(
    `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
  );
  const table = module.ERROR_TABLE;
  if (!table || typeof table !== 'object') throw new Error(`${SOURCE} does not export ERROR_TABLE`);
  for (const [code, spec] of Object.entries(table)) {
    if (!/^[A-Z][A-Z_]+$/.test(code)) throw new Error(`ERROR_TABLE: unexpected code ${code}`);
    for (const key of ['message', 'fix']) {
      if (typeof spec?.[key] !== 'string' || !spec[key].trim())
        throw new Error(`ERROR_TABLE.${code}.${key} is empty`);
    }
    if (!(spec.level in LEVELS)) throw new Error(`ERROR_TABLE.${code}.level is ${spec.level}`);
  }
  return table;
}

/** Markdown text: `<` would start an HTML tag outside code spans. */
function text(value) {
  return value
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replaceAll('<', '&lt;')))
    .join('')
    .trim();
}

function cell(value) {
  return text(value).replaceAll('|', '\\|');
}

function render(table) {
  const codes = Object.keys(table);
  const lines = [
    `<!-- GENERATED by scripts/gen-error-docs.mjs from ${SOURCE} (ERROR_TABLE). Do not edit; run the script. -->`,
    '',
    '# Error codes',
    '',
    'Every failure is a `LocationPickerError` with a stable `code`, a one-line `fix` and a `level`. Its message reads',
    '`[location-picker] <what happened>. Fix: <fix>`.',
    '',
    '- Failures that are not tied to a returned promise fire a cancelable `error` event (it does not bubble) on the',
    '  element or the class instance. When no listener calls `preventDefault()` and no `onError` callback exists, it is',
    '  logged at its `level`.',
    '- Methods (`locate()`, `geocode()`, `lookupAddress()`) and the `ready` promise reject with the same error instead.',
    '- `{placeholders}` in a message are filled in with the details of the failure.',
    '',
    'The level below is the default for each code; a few cases override it (see',
    '[`LocationPickerErrorCode`](api.md#locationpickererrorcode)).',
    '',
    '| Code | Level | Fix |',
    '| --- | --- | --- |',
    ...codes.map(
      (code) =>
        `| [\`${code}\`](#${code.toLowerCase()}) | \`${table[code].level}\` | ${cell(table[code].fix)} |`,
    ),
  ];
  for (const code of codes) {
    const { message, fix, level } = table[code];
    lines.push(
      '',
      `## \`${code}\``,
      '',
      `- **Level:** \`${level}\` (${LEVELS[level]})`,
      `- **Message:** ${text(message)}`,
      `- **Fix:** ${text(fix)}`,
    );
  }
  return `${lines.join('\n')}\n`;
}
