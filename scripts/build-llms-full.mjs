// Builds site/llms-full.txt: the README and the docs/ pages in one Markdown file for language models.
// Deterministic: a fixed file order, no timestamps, LF line endings. HTML comment lines outside code fences
// (doc-test tags, prettier-ignore markers) are dropped, and relative links become absolute GitHub URLs.
//
//   node scripts/build-llms-full.mjs           rewrite site/llms-full.txt
//   node scripts/build-llms-full.mjs --check   fail if site/llms-full.txt is missing or out of date
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';

const OUTPUT = 'site/llms-full.txt';
const REPO = 'https://github.com/cyphercodes/location-picker/blob/master/';
const SOURCES = [
  'README.md',
  'docs/forms.md',
  'docs/embed.md',
  'docs/frameworks.md',
  'docs/providers.md',
  'docs/csp.md',
  'docs/migration.md',
  'docs/troubleshooting.md',
  'docs/errors.md',
  'docs/ai-agents.md',
  'docs/api.md',
];
const check = process.argv.includes('--check');

const { description } = JSON.parse(await readFile('package.json', 'utf8'));
const parts = [
  '# location-picker: full documentation',
  '',
  `> ${description}`,
  '',
  `Generated by scripts/build-llms-full.mjs from the README and docs/ of ${REPO.replace(/\/blob\/master\/$/, '')}. ` +
    'Short version: https://cyphercodes.github.io/location-picker/llms.txt',
];
const present = SOURCES.filter((file) => existsSync(file));
for (const file of SOURCES.filter((f) => !present.includes(f)))
  console.warn(`skipped ${file} (missing)`);
const contents = await Promise.all(present.map((file) => readFile(file, 'utf8')));
present.forEach((file, i) => {
  const markdown = contents[i].replaceAll('\r\n', '\n');
  parts.push('', '---', '', `Source: ${REPO}${file}`, '', clean(markdown, file).trim());
});
const output = `${parts.join('\n')}\n`;

if (check) {
  const committed = existsSync(OUTPUT) ? await readFile(OUTPUT, 'utf8') : '';
  if (committed !== output) {
    console.error(
      `${OUTPUT} is out of date. Run \`node scripts/build-llms-full.mjs\` and commit it.`,
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(OUTPUT, output);
  console.log(`${OUTPUT}: ${Buffer.byteLength(output)} bytes from ${present.length} files`);
}

/** Outside code fences: drops comment-only lines and repeated blank lines, and makes relative links absolute. */
function clean(markdown, file) {
  let fence = null;
  const lines = [];
  for (const line of markdown.split('\n')) {
    if (fence === null) {
      fence = /^\s*(`{3,}|~{3,})/.exec(line)?.[1] ?? null;
      if (fence === null && /^\s*<!--.*-->\s*$/.test(line)) continue;
      if (fence === null && !line.trim() && !lines.at(-1)?.trim()) continue;
      lines.push(fence === null ? absoluteLinks(line, file) : line);
    } else {
      if (line.trim().startsWith(fence) && /^(`+|~+)$/.test(line.trim())) fence = null;
      lines.push(line);
    }
  }
  return lines.join('\n');
}

function absoluteLinks(line, file) {
  return line.replace(/\]\(([^)\s]+)\)/g, (match, target) => {
    if (/^([a-z][a-z+.-]*:|#)/i.test(target)) return match;
    const path = posix.normalize(posix.join(posix.dirname(file), target));
    return `](${REPO}${path})`;
  });
}
